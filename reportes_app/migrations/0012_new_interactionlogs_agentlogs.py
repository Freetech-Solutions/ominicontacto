def create_resumen_transfer_tables(apps, schema_editor):
    """
    Crea las tablas reportes_app_llamada_resumen y reportes_app_transferlog
    con todos sus campos e índices.
    """
    with schema_editor.connection.cursor() as cursor:
        # 1. Crear tabla reportes_app_llamada_resumen
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS public.reportes_app_llamada_resumen (
                id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                callid                      varchar(64) NOT NULL,
                campana_id                  integer,
                tipo_campana                integer,
                tipo_llamada                integer,
                agente_id                   integer,
                contacto_id                 integer,
                numero_marcado              varchar(128),
                fecha_inicio                timestamptz,
                fecha_fin                   timestamptz,
                duracion_segundos           numeric(10,3),
                bridge_wait_time            numeric(10,3),
                event                       varchar(32),
                archivo_grabacion           varchar(256),
                es_transferencia            boolean NOT NULL DEFAULT false,
                calificacion_id             integer,
                opcion_calificacion_id      integer,
                opcion_calificacion_nombre  varchar(100),
                opcion_calificacion_tipo    integer,
                subcalificacion             varchar(200),
                es_venta                    boolean NOT NULL DEFAULT false,
                created_at                  timestamptz NOT NULL DEFAULT now(),
                updated_at                  timestamptz NOT NULL DEFAULT now(),
                atendida_por_voicebot       boolean NOT NULL DEFAULT false,
                atencion_hibrida            boolean NOT NULL DEFAULT false,
                canalidad                   varchar(16) CHECK (canalidad IN ('TEL', 'EMAIL', 'WA', 'FBMSN', 'IGDI', 'SMS')),
                node_id                     varchar(64),
                tenant_id                   varchar(64),
                hangup_trigger              varchar(16) CHECK (hangup_trigger IS NULL OR hangup_trigger IN ('AGENT', 'EXTERNAL', 'OTHER')),

                CONSTRAINT reportes_app_llamada_resumen_callid_key UNIQUE (callid)
            );
        """)

