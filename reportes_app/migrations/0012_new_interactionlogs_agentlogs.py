def reverse_resumen_transfer_tables(apps, schema_editor):
    """
    Elimina las tablas creadas en la migración.
    """
    with schema_editor.connection.cursor() as cursor:
        cursor.execute("DROP TABLE IF EXISTS public.reportes_app_transferlog CASCADE;")
        cursor.execute("DROP TABLE IF EXISTS public.reportes_app_llamada_resumen CASCADE;")


def create_interactions_tables(apps, schema_editor):
    """
    Crea las tablas de interacciones omnicanal:
    - interactions_summary (resumen y KPIs, con wait_conn_duration)
    - interaction_journey (trazabilidad paso a paso)
    - interaction_transfers (transferencias vinculadas al journey)
    """
    with schema_editor.connection.cursor() as cursor:
        # 1. Tabla maestra de interacciones (wait_conn_duration desde el inicio)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS public.interactions_summary (
                id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                interaction_id          VARCHAR(64) NOT NULL UNIQUE,
                tenant_id               VARCHAR(64) NOT NULL,
                node_id                 VARCHAR(64),
                campaign_id             INTEGER,
                channel_type            VARCHAR(16) NOT NULL,
                direction               VARCHAR(16) NOT NULL DEFAULT 'INBOUND',
                initiation_method       VARCHAR(32),
                status                  VARCHAR(32) NOT NULL,
                hangup_cause            VARCHAR(32),
                source_address          VARCHAR(256),
                destination_address     VARCHAR(256),
                start_time              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                end_time                TIMESTAMPTZ,
                total_duration          NUMERIC(10,3) DEFAULT 0,
                bot_duration            NUMERIC(10,3) DEFAULT 0,
                wait_conn_duration      NUMERIC(10,3) DEFAULT 0,
                agent_duration          NUMERIC(10,3) DEFAULT 0,
                agent_id                INTEGER,
                disposition_id          INTEGER,
                customer_id             INTEGER,
                outcome                 BOOLEAN DEFAULT FALSE,
                is_transferred          BOOLEAN DEFAULT FALSE,
                transfer_count          INTEGER DEFAULT 0,
                channel_data            JSONB DEFAULT '{}'::jsonb,
                created_at              TIMESTAMPTZ DEFAULT NOW(),
                updated_at              TIMESTAMPTZ DEFAULT NOW(),
                CONSTRAINT check_direction CHECK (direction IN ('INBOUND', 'OUTBOUND')),
                CONSTRAINT interactions_summary_initiation_method_valid
                    CHECK (initiation_method IS NULL OR initiation_method IN ('AGENT', 'DIALER', 'BOT'))
            );
        """)
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_summ_date
            ON public.interactions_summary (start_time);
        """)
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_summ_tenant_node
            ON public.interactions_summary (tenant_id, node_id);
        """)
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_summ_inter_id
            ON public.interactions_summary (interaction_id);
        """)
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_summ_metadata
            ON public.interactions_summary USING gin (channel_data);
        """)

        # 2. Tabla de customer journey
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS public.interaction_journey (
                id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                interaction_id      VARCHAR(64) NOT NULL,
                sequence_number     INTEGER NOT NULL,
                node_type           VARCHAR(32) NOT NULL,
                node_name           VARCHAR(128),
                action              VARCHAR(32),
                payload             JSONB DEFAULT '{}'::jsonb,
                timestamp           TIMESTAMPTZ DEFAULT NOW()
            );
        """)
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_journey_interaction_seq
            ON public.interaction_journey (interaction_id, sequence_number);
        """)

        # 3. Tabla de transferencias (FK a interaction_journey)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS public.interaction_transfers (
                id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                interaction_id      VARCHAR(64) NOT NULL,
                journey_entry_id    BIGINT REFERENCES public.interaction_journey(id) ON DELETE SET NULL,
                source_agent_id     INTEGER,
                source_channel      VARCHAR(128),
                destination_target  VARCHAR(128) NOT NULL,
                destination_type    VARCHAR(32),
                transfer_type       VARCHAR(20),
                status              VARCHAR(20),
                fail_reason         VARCHAR(64),
                created_at          TIMESTAMPTZ DEFAULT NOW(),
                completed_at        TIMESTAMPTZ,
                talk_time_after     NUMERIC(10,3) DEFAULT 0
            );
        """)
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_transfers_int_id
            ON public.interaction_transfers (interaction_id);
        """)
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_transfers_journey_link
            ON public.interaction_transfers (journey_entry_id);
        """)


def reverse_interactions_tables(apps, schema_editor):
    """
    Elimina las tablas en orden inverso (por la FK interaction_transfers -> interaction_journey).
    """
    with schema_editor.connection.cursor() as cursor:
        cursor.execute("DROP TABLE IF EXISTS public.interaction_transfers CASCADE;")
        cursor.execute("DROP TABLE IF EXISTS public.interaction_journey CASCADE;")
        cursor.execute("DROP TABLE IF EXISTS public.interactions_summary CASCADE;")


