        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_resumen_campana_fecha
            ON public.reportes_app_llamada_resumen (campana_id, fecha_fin);
        """)

        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_resumen_fecha_fin
            ON public.reportes_app_llamada_resumen (fecha_fin);
        """)

        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_resumen_hibrida_fecha
            ON public.reportes_app_llamada_resumen (atencion_hibrida, fecha_fin);
        """)

        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_resumen_venta_fecha
            ON public.reportes_app_llamada_resumen (es_venta, fecha_fin);
        """)

        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_resumen_voicebot_fecha
            ON public.reportes_app_llamada_resumen (atendida_por_voicebot, fecha_fin);
        """)

        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_resumen_node_id
            ON public.reportes_app_llamada_resumen (node_id);
        """)

